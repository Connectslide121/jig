import {
  AlertTriangle,
  CircleHelp,
  Gavel,
  ListChecks,
  RotateCcw,
  Sparkles,
  Square,
  SquareCheck,
  X,
} from "lucide-react";
import type { ReactNode } from "react";
import {
  linesSince,
  notesActions,
  notesModelLabel,
  transcriptEnd,
} from "../../../../../../addons/meetings/lib/notes";
import {
  actionOpen,
  type MeetingAction,
  type MeetingNotesDoc,
  type MeetingRecord,
} from "../../../shared/meetings";
import { Button, CountBadge, cn, Empty, Markdown, type MenuEntry, Spinner } from "../../ui";
import { clock } from "./format";
import { PanelHeader } from "./Panels";

/**
 * A meeting's notes (D-424). Jig writes them silently when you click Generate notes; the state lives on
 * the record, so every window shows the same. Nothing moves: the first notes are a spinner in the
 * notes' own space, new ones keep the old ones dimmed under the spinner, and a failure shows in the
 * same place with Retry. The footer keeps two lines for the AI notice and how stale the notes are.
 */
export function NotesPanel({
  record,
  menu,
  onGenerateNotes,
  onCancelNotes,
  onReview,
  onJump,
}: {
  record: MeetingRecord;
  menu?: MenuEntry[];
  onGenerateNotes(): void;
  /** Stops notes being written, or puts away a failure. */
  onCancelNotes(): void;
  onReview(): void;
  /** Shows a caption in the transcript (a timestamp in the notes). */
  onJump?(at: string): void;
}) {
  const open = record.actions.filter(actionOpen).length;
  const job = record.notesJob;
  const running = job?.state === "running";
  const failed = job?.state === "failed" ? job : undefined;
  const doc = record.notesDoc;
  const hasNotes = Boolean(doc || record.notes.trim());
  const stale = doc ? linesSince(record, doc.through) : 0;
  const notice = doc
    ? `AI-generated by ${notesModelLabel(doc)} · from transcript up to ${clock(transcriptEnd(record, doc.through))} · check important details`
    : hasNotes
      ? "AI-generated · check important details"
      : "";
  return (
    <section className="@container flex size-full min-h-0 min-w-0 flex-col" aria-label="Notes">
      <PanelHeader title="Notes" menu={menu}>
        <Button size="sm" icon={Sparkles} disabled={running} onClick={onGenerateNotes}>
          Generate notes
        </Button>
      </PanelHeader>
      <div className="relative flex min-h-0 flex-1 flex-col">
        <div
          className={cn(
            "min-h-0 flex-1 overflow-y-auto px-4 py-3",
            (running || failed) && hasNotes && "pointer-events-none opacity-40 select-none",
          )}
          aria-busy={running || undefined}
          data-testid="meeting-notes"
        >
          {doc ? (
            <StructuredNotes doc={doc} actions={record.actions} onJump={onJump} />
          ) : record.notes.trim() ? (
            <Markdown text={record.notes} />
          ) : running || failed ? null : (
            <Empty icon={Sparkles} title="No notes yet" className="h-full">
              Jig reads the transcript and writes a summary, decisions, actions and open questions. It only
              runs when you click Generate notes.
            </Empty>
          )}
        </div>
        {running && (
          <div
            className="absolute inset-0 flex items-center justify-center p-4"
            data-testid="meeting-notes-writing"
          >
            {/* Over old notes, a card keeps the spinner and Cancel readable. */}
            <div
              className={cn(
                "flex flex-col items-center gap-3",
                hasNotes && "rounded-md border border-line bg-surface px-6 py-4 shadow-sm",
              )}
            >
              <Spinner size="lg" />
              <Button size="sm" icon={X} onClick={onCancelNotes}>
                Cancel
              </Button>
            </div>
          </div>
        )}
        {failed && (
          <div className="absolute inset-0 flex items-center justify-center p-4">
            <div
              role="alert"
              className="flex w-full max-w-sm flex-col items-center gap-2 rounded-md border border-line bg-surface p-4 text-center shadow-sm"
              data-testid="meeting-notes-failed"
            >
              <AlertTriangle className="size-5 text-danger" />
              <div className="text-sm font-medium">
                {hasNotes ? "Couldn't write new notes" : "Couldn't write the notes"}
              </div>
              <p className="line-clamp-3 text-xs text-muted" title={failed.error}>
                {failed.error ?? "Something went wrong."}
              </p>
              <div className="flex gap-2 pt-1">
                <Button size="sm" variant="primary" icon={RotateCcw} onClick={onGenerateNotes}>
                  Retry
                </Button>
                <Button size="sm" onClick={onCancelNotes}>
                  {hasNotes ? "Keep these notes" : "Dismiss"}
                </Button>
              </div>
            </div>
          </div>
        )}
      </div>
      <div className="flex h-12 shrink-0 items-center gap-2 border-t border-line px-3">
        {/* Two lines always: the AI notice, and how stale the notes are (or what was left out). */}
        <div className="min-w-0 flex-1 text-xs leading-4" data-testid="meeting-notes-footer">
          <div className="truncate text-hint" title={notice || undefined}>
            {notice || " "}
          </div>
          <div className="truncate text-muted">
            {doc && stale > 0 && !running ? (
              <>
                {stale} new {stale === 1 ? "line" : "lines"} since these notes ·{" "}
                <button type="button" className="text-accent hover:underline" onClick={onGenerateNotes}>
                  Regenerate
                </button>
              </>
            ) : doc?.trimmed ? (
              <span className="text-warning">
                Long meeting: {doc.trimmed} lines from the middle were left out
              </span>
            ) : (
              " "
            )}
          </div>
        </div>
        <Button
          icon={ListChecks}
          aria-label="Review actions"
          disabled={!record.actions.length}
          onClick={onReview}
        >
          {/* Narrow (a sidebar): the icon and the count, so the AI notice keeps its room. */}
          <span className="@max-lg:hidden">Review actions</span>
          <span className="flex w-5 justify-end">
            <CountBadge count={open} />
          </span>
        </Button>
      </div>
    </section>
  );
}

const heading = "text-2xs font-semibold tracking-wide text-hint uppercase";

/** A notes section: a small heading over its items. */
function NotesSection({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="space-y-1.5">
      <h3 className={heading}>{title}</h3>
      <ul className="space-y-2">{children}</ul>
    </section>
  );
}

/**
 * One item: an icon in a fixed slot, the text, then who and where (timestamps jump to the transcript),
 * and for actions where they stand at the far right.
 */
function NotesItem({
  icon,
  text,
  who,
  at,
  status,
  onJump,
}: {
  icon: ReactNode;
  text: ReactNode;
  who: ReactNode;
  at: string[];
  status?: string;
  onJump?(at: string): void;
}) {
  return (
    <li className="flex gap-2">
      <span className="flex h-5 w-4 shrink-0 items-center justify-center">{icon}</span>
      <div className="min-w-0 flex-1">
        <p className="leading-5">{text}</p>
        <div className="flex flex-wrap items-center gap-x-2 text-xs text-muted">
          <span className="min-w-0 truncate">{who}</span>
          {at.map((t) =>
            onJump ? (
              <button
                key={t}
                type="button"
                className="text-accent tabular-nums hover:underline"
                title="Show in the transcript"
                onClick={() => onJump(t)}
              >
                {clock(t)}
              </button>
            ) : (
              <span key={t} className="tabular-nums">
                {clock(t)}
              </span>
            ),
          )}
        </div>
      </div>
      {status !== undefined && (
        <span className="w-16 shrink-0 text-right text-xs leading-5 text-hint">{status}</span>
      )}
    </li>
  );
}

const STATUS_LABELS: Record<NonNullable<MeetingAction["status"]>, string> = {
  queued: "Queued",
  running: "Running",
  done: "Done",
  dismissed: "Dismissed",
};

/** Generated notes, laid out by Jig the same way for every meeting (D-424). */
function StructuredNotes({
  doc,
  actions,
  onJump,
}: {
  doc: MeetingNotesDoc;
  actions: MeetingAction[];
  onJump?(at: string): void;
}) {
  const listed = notesActions(actions);
  return (
    <div className="space-y-5 text-sm" data-testid="meeting-notes-doc">
      {doc.tldr && <p className="leading-relaxed text-fg">{doc.tldr}</p>}
      {doc.decisions.length > 0 && (
        <NotesSection title="Decisions">
          {doc.decisions.map((d, i) => (
            <NotesItem
              key={i}
              icon={<Gavel className="size-3.5 text-muted" />}
              text={d.what}
              who={`Decided by ${d.by}`}
              at={d.at}
              onJump={onJump}
            />
          ))}
        </NotesSection>
      )}
      {listed.length > 0 && (
        <NotesSection title="Action items">
          {listed.map((a) => (
            <NotesItem
              key={a.id}
              icon={
                a.status === "done" ? (
                  <SquareCheck className="size-3.5 text-success" />
                ) : (
                  <Square className="size-3.5 text-muted" />
                )
              }
              text={a.title}
              who={`${a.mine ? "You" : a.owner || "Unknown"}${a.due ? ` · due ${a.due}` : ""}`}
              at={a.at ?? []}
              status={a.status ? STATUS_LABELS[a.status] : ""}
              onJump={onJump}
            />
          ))}
        </NotesSection>
      )}
      {doc.questions.length > 0 && (
        <NotesSection title="Open questions and risks">
          {doc.questions.map((q, i) => (
            <NotesItem
              key={i}
              icon={
                q.kind === "risk" ? (
                  <AlertTriangle className="size-3.5 text-warning" />
                ) : (
                  <CircleHelp className="size-3.5 text-muted" />
                )
              }
              text={q.text}
              who={`${q.kind === "risk" ? "Risk" : "Question"} · raised by ${q.raisedBy}`}
              at={q.at}
              onJump={onJump}
            />
          ))}
        </NotesSection>
      )}
      {doc.topics.length > 0 && (
        <section className="space-y-1.5">
          <h3 className={heading}>Discussion</h3>
          <div className="space-y-3">
            {doc.topics.map((t, i) => (
              <div key={i}>
                <div className="font-medium">{t.title}</div>
                <ul className="list-disc space-y-0.5 pl-5 marker:text-hint">
                  {t.points.map((p, j) => (
                    <li key={j}>{p}</li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
        </section>
      )}
      {doc.participants.length > 0 && (
        <section className="space-y-1.5">
          <h3 className={heading}>Participants</h3>
          <p className="text-muted">{doc.participants.join(", ")}</p>
        </section>
      )}
    </div>
  );
}
