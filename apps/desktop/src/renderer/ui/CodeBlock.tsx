import { Check, Copy } from "lucide-react";
import { useEffect, useState } from "react";
import { highlight } from "../lib/highlight";
import { useAppearance } from "../stores/appearance";
import { cn } from "./cn";

/** A code block highlighted with the active theme's own syntax colours (Shiki). */
export function CodeBlock({ code, lang, className }: { code: string; lang?: string; className?: string }) {
  const version = useAppearance((s) => s.highlightVersion);
  const [html, setHtml] = useState<string>();
  const [copied, setCopied] = useState(false);
  // biome-ignore lint/correctness/useExhaustiveDependencies: `version` re-highlights after a theme change.
  useEffect(() => {
    let cancelled = false;
    void highlight(code, lang).then((result) => {
      if (!cancelled) setHtml(result);
    });
    return () => {
      cancelled = true;
    };
  }, [code, lang, version]);
  return (
    <div
      className={cn("group relative my-2 overflow-hidden rounded-md border border-line bg-code", className)}
    >
      <div className="flex h-6 items-center justify-between border-b border-line px-2 text-2xs text-hint">
        <span>{lang ?? "text"}</span>
        <button
          type="button"
          aria-label="Copy code"
          className="flex items-center gap-1 opacity-0 group-hover:opacity-100 group-focus-within:opacity-100 hover:text-fg"
          onClick={() => {
            void navigator.clipboard.writeText(code);
            setCopied(true);
            setTimeout(() => setCopied(false), 1200);
          }}
        >
          {copied ? <Check className="size-3" /> : <Copy className="size-3" />}
          {copied ? "Copied" : "Copy"}
        </button>
      </div>
      {html ? (
        <div
          className="selectable jig-code overflow-x-auto p-2 font-mono text-xs"
          // Shiki's output: escaped code wrapped in spans with colour styles.
          // biome-ignore lint/security/noDangerouslySetInnerHtml: generated by Shiki from escaped text.
          dangerouslySetInnerHTML={{ __html: html }}
        />
      ) : (
        <pre className="selectable overflow-x-auto p-2 font-mono text-xs text-fg">{code}</pre>
      )}
    </div>
  );
}
